def test_bulk_import_new_instrument(
    tmp_path,
):
    db = tmp_path / "stage3.db"
    import_file = (
        tmp_path
        / "fineco_smci.json"
    )

    _write_import_file(
        import_file
    )

    store = Stage3Store(
        db
    )

    importer = FinecoBulkImporter(
        store
    )

    result = importer.import_file(
        import_file
    )

    assert result.new_count == 1
    assert result.update_count == 0
    assert result.unchanged_count == 0
    assert result.error_count == 0

    assert len(
        result.items
    ) == 1

    assert (
        result.items[0].action
        == ImportAction.NEW
    )

    instruments = (
        store.find_fineco_instruments(
            "SMCI"
        )
    )

    assert len(
        instruments
    ) == 1

    instrument = (
        instruments[0]
    )

    assert (
        instrument.underlying
        == "SMCI"
    )

    assert (
        instrument.fineco_symbol
        == "SMCI.O"
    )

    assert (
        instrument.broker_leverage
        == 1
    )

    assert (
        instrument.embedded_leverage
        == 1
    )


