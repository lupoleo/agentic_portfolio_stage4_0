def _make_waiting_opportunity(
    *,
    opportunity_id: str,
    ticker: str,
) -> TradeOpportunity:

    now = datetime(
        2026,
        8,
        18,
        8,
        0,
        0,
        tzinfo=timezone.utc,
    )

    return TradeOpportunity(
        opportunity_id=opportunity_id,
        snapshot_id="SNAP-BULK-TEST",
        created_at=now,
        updated_at=now,

        ticker=ticker,

        direction=Direction.LONG,

        horizon=TradingHorizon.SWING,

        expected_holding_min_days=5,
        expected_holding_max_days=15,

        confidence=0.80,

        target_exposure_eur=5000,
        max_intended_loss_eur=500,

        thesis=(
            "Bulk importer integration test"
        ),

        catalyst=None,

        key_risks=[],
        evidence_ids=[],

        status=(
            OpportunityStatus
            .WAITING_FOR_BROKER_INSTRUMENTS
        ),

        broker_instruments_required=True,

        broker_instruments_available=False,

        broker_instrument_count=0,

        rejection_reason=None,
        expiry_reason=None,

        notes="pytest",
    )

def test_bulk_import_refreshes_waiting_opportunity(
    tmp_path,
):
    db = tmp_path / "stage3.db"

    import_file = (
        tmp_path
        / "fineco_smci.json"
    )

    _write_import_file(
        import_file
    )

    store = Stage3Store(
        db
    )

    opportunity = (
        _make_waiting_opportunity(
            opportunity_id=(
                "OPP-SMCI-WAITING"
            ),
            ticker="SMCI",
        )
    )

    store.save_trade_opportunity(
        opportunity
    )

    before = (
        store.get_trade_opportunity(
            opportunity.opportunity_id
        )
    )

    assert before is not None

    assert (
        before.status
        == OpportunityStatus
        .WAITING_FOR_BROKER_INSTRUMENTS
    )

    importer = FinecoBulkImporter(
        store
    )

    result = importer.import_file(
        import_file
    )

    assert (
        result.error_count
        == 0
    )

    assert (
        result.new_count
        == 1
    )

    assert (
        result.refreshed_opportunity_count
        == 1
    )

    assert (
        result.refreshed_opportunity_ids
        == [
            "OPP-SMCI-WAITING"
        ]
    )

    after = (
        store.get_trade_opportunity(
            opportunity.opportunity_id
        )
    )

    assert after is not None

    assert (
        after.status
        == OpportunityStatus
        .READY_FOR_INSTRUMENT_SELECTION
    )

    assert (
        after.broker_instruments_available
        is True
    )

    assert (
        after.broker_instrument_count
        == 1
    )

def test_bulk_import_dry_run_does_not_refresh_opportunity(
    tmp_path,
):
    db = tmp_path / "stage3.db"

    import_file = (
        tmp_path
        / "fineco_smci.json"
    )

    _write_import_file(
        import_file
    )

    store = Stage3Store(
        db
    )

    opportunity = (
        _make_waiting_opportunity(
            opportunity_id=(
                "OPP-SMCI-DRYRUN"
            ),
            ticker="SMCI",
        )
    )

    store.save_trade_opportunity(
        opportunity
    )

    importer = FinecoBulkImporter(
        store
    )

    result = importer.import_file(
        import_file,
        dry_run=True,
    )

    assert (
        result.refreshed_opportunity_count
        == 0
    )

    assert (
        result.refreshed_opportunity_ids
        == []
    )

    after = (
        store.get_trade_opportunity(
            opportunity.opportunity_id
        )
    )

    assert after is not None

    assert (
        after.status
        == OpportunityStatus
        .WAITING_FOR_BROKER_INSTRUMENTS
    )

    assert (
        after.broker_instruments_available
        is False
    )

    assert (
        after.broker_instrument_count
        == 0
    )

    # Dry-run also must not have inserted
    # the Fineco instrument itself.
    instruments = (
        store.find_fineco_instruments(
            "SMCI"
        )
    )

    assert instruments == []

def test_unchanged_bulk_import_can_refresh_waiting_opportunity(
    tmp_path,
):
    db = tmp_path / "stage3.db"

    import_file = (
        tmp_path
        / "fineco_smci.json"
    )

    _write_import_file(
        import_file
    )

    store = Stage3Store(
        db
    )

    importer = FinecoBulkImporter(
        store
    )

    # First import populates the Fineco cache.
    first = importer.import_file(
        import_file
    )

    assert first.new_count == 1

    # Opportunity is created AFTER the Fineco cache
    # already contains the instrument.
    opportunity = (
        _make_waiting_opportunity(
            opportunity_id=(
                "OPP-SMCI-UNCHANGED"
            ),
            ticker="SMCI",
        )
    )

    store.save_trade_opportunity(
        opportunity
    )

    # Re-importing the same broker file should be
    # UNCHANGED, but must still refresh the opportunity.
    second = importer.import_file(
        import_file
    )

    assert (
        second.new_count
        == 0
    )

    assert (
        second.unchanged_count
        == 1
    )

    assert (
        second.refreshed_opportunity_count
        == 1
    )

    after = (
        store.get_trade_opportunity(
            opportunity.opportunity_id
        )
    )

    assert after is not None

    assert (
        after.status
        == OpportunityStatus
        .READY_FOR_INSTRUMENT_SELECTION
    )
