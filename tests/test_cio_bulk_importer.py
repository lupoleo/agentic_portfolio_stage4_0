def _write_import_file(
    path: Path,
    *,
    description: str = "Super Micro Computer Ordinary",
    broker_leverage: float | None = 1,
) -> None:
    """
    Create one valid Fineco bulk import JSON file.

    The instrument represents SMCI Ordinary on NASDAQ.
    """

    payload = {
        "schema_version": "1.0",
        "batch_name": "Fineco SMCI test",
        "created_at": NOW.isoformat(),
        "notes": "Generated by pytest",
        "instruments": [
            {
                "payload": {
                    "underlying": "SMCI",
                    "reference_underlying": "SMCI",
                    "exposure_relationship": "DIRECT",

                    "description": description,

                    "instrument_type": "ORDINARY",
                    "trading_mode": "ORDINARY",

                    "fineco_symbol": "SMCI.O",
                    "market": "NASDAQ",

                    "quote_currency": "USD",
                    "settlement_currency": "USD",
                    "margin_currency": None,

                    "long_available": True,
                    "short_available": True,

                    "intraday_available": True,
                    "overnight_available": True,

                    "broker_leverage": broker_leverage,
                    "embedded_leverage": 1,

                    "margin_pct": None,

                    "tick_size": 0.01,
                    "tick_currency": "USD",

                    "commission": None,
                    "overnight_financing_pct": None,

                    "certificate_terms": None,
                    "market_snapshot": None,

                    "notes": "Fineco SMCI Ordinary test",
                }
            }
        ],
    }

    path.write_text(
        json.dumps(
            payload,
            indent=2,
        ),
        encoding="utf-8",
    )


