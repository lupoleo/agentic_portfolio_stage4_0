def test_bulk_import_updates_existing_instrument(
    tmp_path,
):
    db = tmp_path / "stage3.db"

    original_file = (
        tmp_path
        / "smci_original.json"
    )

    updated_file = (
        tmp_path
        / "smci_updated.json"
    )

    _write_import_file(
        original_file,
        description=(
            "Super Micro Computer Ordinary"
        ),
    )

    _write_import_file(
        updated_file,
        description=(
            "Super Micro Computer "
            "Ordinary NASDAQ"
        ),
    )

    store = Stage3Store(
        db
    )

    importer = FinecoBulkImporter(
        store
    )

    first = importer.import_file(
        original_file
    )

    assert (
        first.new_count
        == 1
    )

    before = (
        store.find_fineco_instruments(
            "SMCI"
        )[0]
    )

    original_id = (
        before.instrument_id
    )

    second = importer.import_file(
        updated_file
    )

    assert (
        second.new_count
        == 0
    )

    assert (
        second.update_count
        == 1
    )

    assert (
        second.unchanged_count
        == 0
    )

    assert (
        second.error_count
        == 0
    )

    after = (
        store.find_fineco_instruments(
            "SMCI"
        )[0]
    )

    # Update must preserve stable identity.
    assert (
        after.instrument_id
        == original_id
    )

    assert (
        after.description
        == (
            "Super Micro Computer "
            "Ordinary NASDAQ"
        )
    )


